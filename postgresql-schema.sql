    p_aid integer
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_did  integer;
    v_ri   double precision;
    v_pt   integer;
    v_avg  double precision;
BEGIN
    SELECT doctorid INTO v_did
    FROM dbo.appointment
    WHERE appointid = p_aid;

    SELECT reputeindex, patients_treated
    INTO v_ri, v_pt
    FROM dbo.doctor
    WHERE doctorid = v_did;

