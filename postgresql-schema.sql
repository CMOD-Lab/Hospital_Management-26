CREATE OR REPLACE VIEW dbo.deptinfo AS
SELECT
    deptname,
    description,
    count(dept.deptno) AS "Number of Doctors"
FROM dbo.department dept
JOIN dbo.doctor d ON dept.deptno = d.deptno
WHERE d.status <> 0
GROUP BY dept.deptno, deptname, description;

