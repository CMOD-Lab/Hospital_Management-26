-- Original: DontDeleteFunction, DontDeleteProcedure, DontDeleteTable, DontDeleteView
-- These were SQL Server DDL triggers ON DATABASE FOR DROP_FUNCTION/PROCEDURE/TABLE/VIEW
-- PostgreSQL equivalent: event triggers using ddl_command_start
-- NOTE: Event triggers require superuser or event_trigger privilege.
--       They fire on ddl_command_start and can raise exceptions to prevent DDL.
-- =============================================================================

-- Trigger function: prevent DROP FUNCTION
CREATE OR REPLACE FUNCTION dbo.trg_prevent_drop_function()
RETURNS event_trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF tg_tag = 'DROP FUNCTION' THEN
        RAISE EXCEPTION 'Function Deletion is Not Allowed';
    END IF;
END;
$$;

CREATE EVENT TRIGGER dontdeletefunction
    ON ddl_command_start
    WHEN TAG IN ('DROP FUNCTION')
    EXECUTE FUNCTION dbo.trg_prevent_drop_function();

-- Trigger function: prevent DROP PROCEDURE
CREATE OR REPLACE FUNCTION dbo.trg_prevent_drop_procedure()
RETURNS event_trigger
LANGUAGE plpgsql
AS $$
BEGIN
