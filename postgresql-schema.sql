--   - DATEDIFF(YEAR, BirthDate, GETDATE()) →
--     EXTRACT(YEAR FROM AGE(CURRENT_TIMESTAMP, birthdate))::integer
--   - No RETURN value statement (OUT parameters returned automatically)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.get_doctor_profile(
    p_did           integer,
    OUT p_name      varchar(20),
    OUT p_phone     char(15),
    OUT p_gender    varchar(2),
    OUT p_charges   double precision,
    OUT p_ri        double precision,
    OUT p_ptreated  integer,
    OUT p_qualification  varchar(100),
    OUT p_specialization varchar(50),
    OUT p_worke     integer,
    OUT p_age       integer
)
RETURNS SETOF record
LANGUAGE plpgsql
AS $$
BEGIN
    SELECT
        d.name,
        d.phone,
        d.gender,
        d.charges_per_visit,
        d.reputeindex,
        d.patients_treated,
        d.qualification,
