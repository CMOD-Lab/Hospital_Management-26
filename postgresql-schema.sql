-- -----------------------------------------------------------------------------
-- Function: dbo.retrievefreeslots
-- Original: [dbo].[RetrieveFreeSlots]
-- Changes:
--   - WHILE loop preserved; DATEPART → EXTRACT
--   - GETDATE() → CURRENT_TIMESTAMP
--   - CAST(@tempHour AS VARCHAR(5)) → v_temphour::varchar(5)
--   - dbo.fnSplitString(@hoursList, ',') → dbo.fnsplitstring(v_hourslist, ',')
--   - Has OUT parameter @count AND a result set → REFCURSOR pattern
--   - ref_slots cursor returns the free slot strings
--   - ref_count cursor returns the count
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.retrievefreeslots(
    p_did           integer,
    p_pid           integer,
    OUT ref_slots   REFCURSOR,
    OUT ref_count   REFCURSOR
)
RETURNS SETOF record
LANGUAGE plpgsql
AS $$
DECLARE
    v_month       integer;
    v_year        integer;
    v_day         integer;
    v_hourslist   varchar(100);
    v_currenthour integer;
    v_count       integer;
    v_tempt       varchar(10);
    v_temphour    integer;
BEGIN
    v_month := EXTRACT(MONTH FROM CURRENT_TIMESTAMP)::integer;
    v_year  := EXTRACT(YEAR  FROM CURRENT_TIMESTAMP)::integer;
    v_day   := EXTRACT(DAY   FROM CURRENT_TIMESTAMP)::integer;

    v_currenthour := 9;
    v_count       := 0;
    v_hourslist   := '';
    v_temphour    := 0;

    WHILE v_currenthour <> 18 LOOP
        IF NOT EXISTS (
            SELECT 1 FROM dbo.appointment
            WHERE EXTRACT(YEAR  FROM date)::integer = v_year
              AND EXTRACT(MONTH FROM date)::integer = v_month
              AND EXTRACT(DAY   FROM date)::integer = v_day
              AND doctorid = p_did
              AND EXTRACT(HOUR  FROM date)::integer = v_currenthour
        ) THEN
            v_count := v_count + 1;

            IF v_currenthour < 12 THEN
                v_tempt    := ':00 AM';
                v_temphour := v_currenthour;
            ELSIF v_currenthour = 12 THEN
                v_tempt    := ':00 PM';
                v_temphour := v_currenthour;
            ELSE
                v_tempt    := ':00 PM';
                v_temphour := v_currenthour - 12;
            END IF;

            v_hourslist := v_hourslist || v_temphour::varchar(5) || v_tempt || ',';
        END IF;

        v_currenthour := v_currenthour + 1;
    END LOOP;

    OPEN ref_slots FOR
        SELECT splitdata AS "Free Slots"
        FROM dbo.fnsplitstring(v_hourslist, ',');

    OPEN ref_count FOR
        SELECT v_count AS count;

    RETURN NEXT;
END;
$$;

