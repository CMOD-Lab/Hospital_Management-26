-- -----------------------------------------------------------------------------
-- Function: dbo.fnsplitstring
-- Original: [dbo].[fnSplitString] (table-valued function)
-- Changes:
--   - NVARCHAR(MAX) → text
--   - CHAR(1) → char(1)
--   - Table-valued function → RETURNS TABLE using RETURN QUERY with
--     regexp_split_to_table for idiomatic PostgreSQL
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.fnsplitstring(
    p_string    text,
    p_delimiter char(1)
)
RETURNS TABLE(splitdata text)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT s.val
    FROM regexp_split_to_table(p_string, regexp_quote(p_delimiter::text)) AS s(val)
    WHERE s.val <> '';
END;
$$;

-- Helper: regexp_quote is not built-in; create a simple escape helper
-- (used internally by fnsplitstring to escape the delimiter for regexp)
CREATE OR REPLACE FUNCTION dbo.regexp_quote(p_str text)
RETURNS text
LANGUAGE sql
IMMUTABLE STRICT
AS $$
    SELECT regexp_replace(p_str, '([!$()*+.:<=>?[\\\]^{|}-])', '\\\1', 'g');
$$;

-- -----------------------------------------------------------------------------
-- Function: dbo.adddoctor
-- Original: [dbo].[AddDoctor]
-- Changes:
--   - @variable → p_variable naming
--   - INSERT INTO LoginTable values(...) → explicit column list (required)
--   - INSERT INTO Doctor values(...) → explicit column list (required)
--   - SCOPE_IDENTITY() / @@IDENTITY → lastval() / RETURNING
--   - Single result set (no output) → RETURNS void
-- NOTE: Original INSERT INTO LoginTable/Doctor used positional VALUES without
--       column names. Explicit column names added for PostgreSQL compatibility.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.adddoctor(
    p_name      varchar(50),
    p_email     varchar(50),
    p_password  varchar(50),
    p_birthdate date,
    p_dept      integer,
    p_gender    char(1),
    p_address   varchar(50),
    p_exp       integer,
    p_salary    integer,
    p_spec      varchar(50),
    p_phone     varchar(50),
    p_charges   integer,
    p_qual      varchar(50)
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_id integer;
BEGIN
    INSERT INTO dbo.logintable (password, email, type)
    VALUES (p_password, p_email, 2);

    SELECT loginid INTO v_id
    FROM dbo.logintable
    WHERE email = p_email;

    INSERT INTO dbo.doctor (
        doctorid, name, phone, address, birthdate, gender,
        deptno, charges_per_visit, monthlysalary, reputeindex,
        patients_treated, qualification, specialization, work_experience, status
    )
    VALUES (
        v_id, p_name, p_phone, p_address, p_birthdate, p_gender,
        p_dept, p_charges, p_salary, 0,
        0, p_qual, p_spec, p_exp, -1
    );
END;
$$;

