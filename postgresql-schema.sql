        COALESCE(a.prescription::varchar, 'NA')         AS prescription,
        a.appointment_status
    FROM dbo.appointment a
    JOIN dbo.patient p ON a.patientid = p.patientid
    WHERE a.doctorid = p_doc_id
      AND a.appointment_status = 1
      AND DATE(a.date) = CURRENT_DATE;
END;
$$;

-- -----------------------------------------------------------------------------
-- Function: dbo.updateprescription
-- Original: [dbo].[UpdatePrescription]
-- Changes: Simple UPDATE; RETURNS void
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.updateprescription(
    p_docid       integer,
    p_appointid   integer,
    p_disease     varchar(30),
    p_progress    varchar(50),
    p_prescription varchar(60)
)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE dbo.appointment
    SET disease             = p_disease,
        progress            = p_progress,
        prescription        = p_prescription,
        appointment_status  = 3,
        patientnotification = 2,
        feedbackstatus      = 2
    WHERE appointid = p_appointid;
END;
$$;

