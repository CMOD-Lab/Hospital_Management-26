    p_pid       integer,
    p_did       integer,
    p_freeslot  integer
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_slot  integer;
    v_datea timestamp without time zone;
BEGIN
    v_slot := p_freeslot;
    IF v_slot < 9 THEN
        v_slot := v_slot + 12;
    END IF;

    -- Build today's date at the given hour slot
    v_datea := date_trunc('day', CURRENT_TIMESTAMP) + (v_slot * INTERVAL '1 hour');

    INSERT INTO dbo.appointment (
        doctorid, patientid, date, appointment_status,
        bill_amount, bill_status, doctornotification, patientnotification,
        feedbackstatus, disease, progress, prescription
    )
    VALUES (
        p_did, p_pid, v_datea, 2,
        NULL, NULL, 2, 1,
        NULL, NULL, NULL, NULL
    );
END;
$$;

