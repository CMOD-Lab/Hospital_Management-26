    p_password  varchar(20),
    OUT p_status integer,
    OUT p_id     integer,
    OUT p_type   integer
)
RETURNS SETOF record
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM dbo.logintable WHERE email = p_email) THEN
        IF p_password = (SELECT password FROM dbo.logintable WHERE email = p_email) THEN
            SELECT loginid, type
            INTO p_id, p_type
            FROM dbo.logintable
            WHERE email = p_email;
