-- -----------------------------------------------------------------------------
-- View: dbo.income
-- Original: [dbo].[Income]
-- Changes:
--   - DATEDIFF(MONTH, date, GETDATE()) = 0 →
--     DATE_PART('year', AGE(CURRENT_TIMESTAMP, date)) * 12 +
--     DATE_PART('month', AGE(CURRENT_TIMESTAMP, date)) = 0
--     (simplified: same month/year check using date_trunc)
--   - GETDATE() → CURRENT_TIMESTAMP
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW dbo.income AS
SELECT SUM(bill_amount) AS income
FROM dbo.appointment
WHERE appointment.bill_status = 'Paid'
  AND DATE_PART('year',  AGE(CURRENT_TIMESTAMP, appointment.date)) * 12
    + DATE_PART('month', AGE(CURRENT_TIMESTAMP, appointment.date)) = 0;

-- -----------------------------------------------------------------------------
-- View: dbo.department_view
-- Original: [dbo].[Department_View]
-- Changes:
--   - SELECT TOP 20 ... ORDER BY → SELECT ... ORDER BY ... LIMIT 20
--     (LIMIT must appear at end of query; ORDER BY inside a plain view is
--      not guaranteed in PostgreSQL — wrapped in a subquery for correctness)
--   - WITH SCHEMABINDING removed (not supported in PostgreSQL)
-- NOTE: PostgreSQL does not allow ORDER BY in a plain view without LIMIT.
--       The TOP 20 + ORDER BY is preserved via a subquery.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW dbo.department_view AS
SELECT id, name, description, "Number of Doctors"
FROM (
    SELECT
        department.deptno   AS id,
        department.deptname AS name,
        department.description,
        count(department.deptno) AS "Number of Doctors"
    FROM dbo.department
    JOIN dbo.doctor ON department.deptno = doctor.deptno
    WHERE doctor.status <> 0
    GROUP BY department.deptno, department.deptname, department.description
    ORDER BY department.deptno
    LIMIT 20
) sub;

-- -----------------------------------------------------------------------------
-- View: dbo.appointment_view
-- Original: [dbo].[Appointment_view]
-- Changes:
--   - DATEDIFF(MONTH, A.Date, GETDATE()) = 0 → same-month check via AGE()
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW dbo.appointment_view AS
SELECT
    a.appointid,
    doctor.name,
    patient.patientid,
    a.date
FROM dbo.appointment a
JOIN dbo.patient   ON patient.patientid = a.patientid
JOIN dbo.doctor    ON doctor.doctorid   = a.doctorid
WHERE DATE_PART('year',  AGE(CURRENT_TIMESTAMP, a.date)) * 12
    + DATE_PART('month', AGE(CURRENT_TIMESTAMP, a.date)) = 0;

