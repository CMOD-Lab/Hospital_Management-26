-- -----------------------------------------------------------------------------
-- Function: dbo.retrievecurrentappointment
-- Original: [dbo].[RetrieveCurrentAppointment]
-- Changes:
--   - Three OUT parameters + complex logic → RETURNS SETOF record
--   - DATEPART(day/month/year, ...) → EXTRACT(... FROM ...)
--   - CONVERT(VARCHAR(19), [date]) → TO_CHAR(date, 'YYYY-MM-DD HH24:MI:SS')
--   - GETDATE() → CURRENT_TIMESTAMP
--   - Outdated appointment cleanup logic preserved
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbo.retrievecurrentappointment(
    p_pid       integer,
    OUT p_dname  varchar(30),
    OUT p_timings varchar(30),
    OUT p_count  integer
)
RETURNS SETOF record
LANGUAGE plpgsql
AS $$
DECLARE
    v_day    integer;
    v_month  integer;
    v_year   integer;
    v_aday   integer;
    v_amonth integer;
    v_ayear  integer;
BEGIN
    IF EXISTS (SELECT 1 FROM dbo.appointment WHERE patientid = p_pid AND appointment_status = 2) THEN
        v_day   := EXTRACT(DAY   FROM CURRENT_TIMESTAMP)::integer;
        v_month := EXTRACT(MONTH FROM CURRENT_TIMESTAMP)::integer;
        v_year  := EXTRACT(YEAR  FROM CURRENT_TIMESTAMP)::integer;

        SELECT
            EXTRACT(DAY   FROM date)::integer,
            EXTRACT(MONTH FROM date)::integer,
            EXTRACT(YEAR  FROM date)::integer
        INTO v_aday, v_amonth, v_ayear
        FROM dbo.appointment
        WHERE patientid = p_pid AND appointment_status = 2;

        SELECT d.name, TO_CHAR(a.date, 'YYYY-MM-DD HH24:MI:SS')
        INTO p_dname, p_timings
        FROM dbo.appointment a
        JOIN dbo.doctor d ON a.doctorid = d.doctorid
        WHERE a.patientid = p_pid AND a.appointment_status = 2;

        IF (v_aday <> v_day OR v_amonth <> v_month OR v_ayear <> v_year) THEN
            DELETE FROM dbo.appointment
            WHERE patientid = p_pid AND appointment_status = 2;
            p_count := 3;
        ELSE
            p_count := 2;
        END IF;
    ELSE
        IF EXISTS (SELECT 1 FROM dbo.appointment WHERE patientid = p_pid AND appointment_status = 1) THEN
            SELECT d.name, TO_CHAR(a.date, 'YYYY-MM-DD HH24:MI:SS')
            INTO p_dname, p_timings
            FROM dbo.appointment a
            JOIN dbo.doctor d ON a.doctorid = d.doctorid
            WHERE a.patientid = p_pid AND a.appointment_status = 1;
            p_count := 1;
        ELSE
            p_count := 0;
        END IF;
    END IF;

    RETURN NEXT;
END;
$$;

